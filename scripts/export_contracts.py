"""Generate browser wire types from public OpenAPI; unsupported schemas fail closed."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + separator.join(ts(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if kind in ("string", "boolean", "null"):
        return kind
    if kind in ("integer", "number"):
        return "number"
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if kind == "object":
        required = set(schema.get("required", []))
        props = [json.dumps(name) + ("" if name in required else "?") + ": " + ts(value) + ";"
                 for name, value in schema.get("properties", {}).items()]
        additional = schema.get("additionalProperties", not props)
        if additional:
            props.append("[key: string]: " + (ts(additional) if isinstance(additional, dict) else "unknown") + ";")
        return "{ " + " ".join(props) + " }"
    if not schema or set(schema) <= {"title", "description", "default"}:
        return "unknown"
    raise ValueError(f"Unsupported public schema: {schema}")


def generate():
    schemas = json.loads((ROOT / "prototype/openapi.json").read_text())["components"]["schemas"]
    return "// Generated by scripts/export_contracts.py. Do not edit.\n" + "\n".join(
        f"export type {name} = {ts(schema)};" for name, schema in sorted(schemas.items())
    ) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "frontend/src/generated-api.ts"
    content = generate()
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit("Generated API types drifted. Run scripts/export_contracts.py.")
    else:
        target.write_text(content, encoding="utf-8")
